"""Text functions for the billing service."""


def slug(values, limit=3):
    """Text helper: keep the values that pass the text check, at most limit."""
    kept = []
    for value in values:
        if len(kept) >= limit:
            break
        if value is not None and str(value).strip():
            kept.append(value)
    return kept


