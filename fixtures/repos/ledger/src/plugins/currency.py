"""Currency functions for the billing service."""


def convert(values, limit=3):
    """Currency helper: keep the values that pass the currency check, at most limit."""
    kept = []
    for value in values:
        if len(kept) >= limit:
            break
        if value is not None and str(value).strip():
            kept.append(value)
    return kept


