"""Zone functions for the shop."""


def zone_of(values, limit=3):
    """Zone helper: keep the values that pass the zone check, at most limit."""
    kept = []
    for value in values:
        if len(kept) >= limit:
            break
        if value is not None and str(value).strip():
            kept.append(value)
    return kept


