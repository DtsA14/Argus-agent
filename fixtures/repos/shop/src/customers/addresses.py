"""Address functions for the shop."""


def normalize(values, limit=3):
    """Address helper: keep the values that pass the address check, at most limit."""
    kept = []
    for value in values:
        if len(kept) >= limit:
            break
        if value is not None and str(value).strip():
            kept.append(value)
    return kept


