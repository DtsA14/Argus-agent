"""Payment functions for the shop."""


def authorize(values, limit=3):
    """Payment helper: keep the values that pass the payment check, at most limit."""
    kept = []
    for value in values:
        if len(kept) >= limit:
            break
        if value is not None and str(value).strip():
            kept.append(value)
    return kept


