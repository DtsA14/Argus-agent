"""Session functions for the shop."""


def start_session(values, limit=3):
    """Session helper: keep the values that pass the session check, at most limit."""
    kept = []
    for value in values:
        if len(kept) >= limit:
            break
        if value is not None and str(value).strip():
            kept.append(value)
    return kept


